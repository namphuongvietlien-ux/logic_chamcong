def _pyinstaller() -> Path:
    win = ROOT / ".venv" / "Scripts" / "pyinstaller.exe"
    nix = ROOT / ".venv" / "bin" / "pyinstaller"
    if win.exists():
        return win
    if nix.exists():
        return nix
    return Path(sys.executable).with_name("pyinstaller.exe" if os.name == "nt" else "pyinstaller")


def main() -> int:
    os.chdir(ROOT)
    onedir = "--onedir" in sys.argv
    exe = _pyinstaller()
    if onedir:
        spec = SPEC_ONEDIR
        print("Building onedir (dist\\AttendanceApp\\). Distribute the entire folder.")
    else:
        spec = _write_onefile_spec()
        print(f"CustomTkinter assets: {_ctk_dir()}")
        print("Building onefile windowed exe (dist\\AttendanceApp.exe).")
        print("First launch unpacks to a temp folder and can take a minute (EasyOCR/torch).")
        print("Database is created next to the exe (hr_system.db) — not inside _MEIPASS.")
    if not spec.exists():
        print(f"Missing spec: {spec}", file=sys.stderr)
        return 1
    cmd = [str(exe), "--noconfirm", str(spec)]
    if "--clean" in sys.argv:
        cmd.insert(1, "--clean")
    print(" ".join(cmd))
    return subprocess.call(cmd)


if __name__ == "__main__":
    raise SystemExit(main())
