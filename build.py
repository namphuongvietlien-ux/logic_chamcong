"""Build a windowed standalone AttendanceApp.exe.

Default: --onefile --noconsole so other PCs do not need Python or a _internal folder.
SQLite still lives next to the exe (processing.resources.writable_dir), never in _MEIPASS.

Usage (from D:\\chamcong):
    .\\.venv\\Scripts\\python.exe build.py
    .\\.venv\\Scripts\\python.exe build.py --onedir
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC_ONEFILE = ROOT / "AttendanceApp.onefile.spec"
SPEC_ONEDIR = ROOT / "AttendanceApp.spec"


def _ctk_dir() -> Path:
    import customtkinter

    return Path(customtkinter.__file__).resolve().parent


